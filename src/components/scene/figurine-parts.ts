/* ---- Path helpers --------------------------------------------------------- */

const ARGS: Record<string, number> = { M: 2, L: 2, H: 1, V: 1, Q: 4, C: 6, A: 7, Z: 0 };

/** Mirror an absolute M/L/H/V/Q/C/A/Z path about x = 100 (arcs flip their sweep). */
export function mirrorPath(d: string) {
  const tokens = d.match(/[MLHVQCAZ]|-?\d*\.?\d+/g) ?? [];
  const out: string[] = [];
  let cmd = '';
  let i = 0;
  while (i < tokens.length) {
    const t = tokens[i];
    if (/[A-Z]/.test(t)) {
      if (!(t in ARGS)) throw new Error(`mirrorPath: unsupported command ${t}`);
      cmd = t;
      out.push(t);
      i += 1;
      if (cmd === 'Z') continue;
    }
    const n = ARGS[cmd];
    const nums = tokens.slice(i, i + n).map(Number);
    i += n;
    if (cmd === 'H') out.push(fmt(200 - nums[0]));
    else if (cmd === 'V') out.push(fmt(nums[0]));
    else if (cmd === 'A') out.push([nums[0], nums[1], -nums[2], nums[3], 1 - nums[4], 200 - nums[5], nums[6]].map(fmt).join(' '));
    else out.push(nums.map((v, k) => fmt(k % 2 === 0 ? 200 - v : v)).join(' '));
  }
  return out.join(' ');
}

const fmt = (v: number) => String(Math.round(v * 100) / 100);

/** All numeric points of a path (used for centroids and bounds). */
export function pathPoints(d: string): Array<[number, number]> {
  const tokens = d.match(/[MLHVQCZA]|-?\d*\.?\d+/g) ?? [];
  const pts: Array<[number, number]> = [];
  let cmd = '';
  let x = 0;
  let y = 0;
  let i = 0;
  while (i < tokens.length) {
    const t = tokens[i];
    if (/[A-Z]/.test(t)) {
      cmd = t;
      i += 1;
      if (cmd === 'Z') continue;
    }
    if (cmd === 'A') {
      // rx ry rot large sweep x y
      x = Number(tokens[i + 5]);
      y = Number(tokens[i + 6]);
      i += 7;
      pts.push([x, y]);
      continue;
    }
    const n = ARGS[cmd] ?? 2;
    const nums = tokens.slice(i, i + n).map(Number);
    i += n;
    if (cmd === 'H') x = nums[0];
    else if (cmd === 'V') y = nums[0];
    else {
      for (let k = 0; k < nums.length; k += 2) pts.push([nums[k], nums[k + 1]]);
      x = nums[nums.length - 2];
      y = nums[nums.length - 1];
      continue;
    }
    pts.push([x, y]);
  }
  return pts;
}

function circle(cx: number, cy: number, r: number) {
  return `M${fmt(cx - r)} ${fmt(cy)}A${r} ${r} 0 1 0 ${fmt(cx + r)} ${fmt(cy)}A${r} ${r} 0 1 0 ${fmt(cx - r)} ${fmt(cy)}Z`;
}

/* A quilled coil: an Archimedean spiral wound clockwise from the centre. */
function coil(cx: number, cy: number, r: number) {
  const turns = 1.75;
  const steps = 14;
  const pts: Array<[number, number]> = [];
  for (let s = 0; s <= steps; s += 1) {
    const t = s / steps;
    const a = t * turns * Math.PI * 2 - Math.PI / 2;
    const rr = r * (0.12 + 0.68 * t);
    pts.push([cx + Math.cos(a) * rr, cy + Math.sin(a) * rr]);
  }
  let d = `M${fmt(pts[0][0])} ${fmt(pts[0][1])}`;
  for (let s = 1; s < pts.length - 1; s += 1) {
    const mx = (pts[s][0] + pts[s + 1][0]) / 2;
    const my = (pts[s][1] + pts[s + 1][1]) / 2;
    d += `Q${fmt(pts[s][0])} ${fmt(pts[s][1])} ${fmt(mx)} ${fmt(my)}`;
  }
  const last = pts[pts.length - 1];
  return `${d}L${fmt(last[0])} ${fmt(last[1])}`;
}

