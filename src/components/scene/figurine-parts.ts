/*
  Rifqi paper puppet — the single source for every view of the character
  (docs/art-motion-upgrade.md §2, DesignRules.md §2.6).

  Every body part is a flat cut-out sheet in poster units (x 0–200, y 0–460,
  y down) at a depth z (toward the viewer). Parts hang from joints that pivot
  like a paper marionette. The 2D poster, bust, EQbot avatar and 404 pose draw
  these parts flat (orthographic projection, see figurine-rig.ts); the 3D view
  extrudes the same paths, so every view stays one drawing.

  Paths are written with absolute M/L/H/V/Q/C/A/Z commands only, so the right
  side can be generated by mirroring the left (x → 200 − x).
*/

