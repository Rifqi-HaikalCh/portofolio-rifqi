function limb(parts: LimbPart[], side: Side): Part[] {
  return parts.map(({ key, joint, inner, outer, ...rest }) => {
    const id = `${key}-${side}` as const;
    const jointId = `${joint}${side}` as JointId;
    if (side === 'L') {
      return {
        ...rest,
        id,
        joint: jointId,
        shade: inner && outer ? { day: inner, night: outer } : undefined,
      };
    }
    return {
      ...rest,
      id,
      joint: jointId,
      d: mirrorPath(rest.d),
      // Mirrored, the right limb's outer face is the one away from the window.
      shade: inner && outer ? { day: mirrorPath(outer), night: mirrorPath(inner) } : undefined,
    };
  });
}

/* Central parts: shade drawn for daylight; night is its mirror. */
function centered(part: Omit<Part, 'shade'> & { shadeDay?: string }): Part {
  const { shadeDay, ...rest } = part;
  return shadeDay ? { ...rest, shade: { day: shadeDay, night: mirrorPath(shadeDay) } } : rest;
}

/* Paired face parts: left drawn, right mirrored. */
function pair(part: Part): Part[] {
  return [
    { ...part, id: `${part.id}-L` },
    { ...part, id: `${part.id}-R`, d: mirrorPath(part.d) },
  ];
}

